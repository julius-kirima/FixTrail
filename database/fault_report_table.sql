CREATE TABLE public.fault_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_name TEXT NOT NULL,
  title TEXT NOT NULL , 
  category TEXT NOT NULL , 
  location TEXT NOT NULL ,
  description TEXT NOT NULL ,
  status TEXT NOT NULL default 'open' 
      CHECK (
        status IN ('open' , 'in_progress' , 'resolved')
      ),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.fault_reports DISABLE ROW LEVEL SECURITY ;


GRANT SELECT , INSERT , UPDATE ON public.fault_reports to anon ;

GRANT USAGE , SELECT ON SEQUENCE public.fault_reports_id_seq TO anon;

--grants allow the public anon role to read, submit, and update reports while RLS is disabled--

